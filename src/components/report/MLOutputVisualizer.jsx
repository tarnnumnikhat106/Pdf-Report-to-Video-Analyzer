import React, { useState } from 'react';
import {
  Cpu,
  Copy,
  Check,
  Code2,
  LayoutGrid,
  Sliders,
  TrendingUp,
  ShieldCheck,
  ShieldAlert
} from 'lucide-react';
import Card from '../common/Card';

// Friendly parameter name mappings and units
