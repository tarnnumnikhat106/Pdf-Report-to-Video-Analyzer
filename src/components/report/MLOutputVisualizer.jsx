  // CBC
  Age: { label: 'Age', unit: 'yrs' },
  Gender: { label: 'Biological Sex', unit: '', format: (v) => (v === 1 || v === '1' ? 'Female' : 'Male') },
  Hemoglobin: { label: 'Hemoglobin', unit: 'g/dL', normal: '12.0 - 17.5' },
  Platelet_Count: { label: 'Platelet Count', unit: '/µL', normal: '150,000 - 450,000' },
  White_Blood_Cells: { label: 'White Blood Cells (WBC)', unit: '/µL', normal: '4,500 - 11,000' },
  Red_Blood_Cells: { label: 'Red Blood Cells (RBC)', unit: 'x10^6/µL', normal: '4.0 - 5.9' },
  MCV: { label: 'Mean Corpuscular Volume (MCV)', unit: 'fL', normal: '80 - 100' },
  MCH: { label: 'Mean Corpuscular Hemoglobin (MCH)', unit: 'pg', normal: '27 - 33' },
